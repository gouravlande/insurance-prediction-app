# Import Chi-Square test function
from scipy.stats import chi2_contingency

# Import pandas
import pandas as pd

# Significance level
alpha = 0.05

# Convert continuous target column 'charges'
# into 4 groups (bins)
df_cleaned['charges_bin'] = pd.qcut(
    df_cleaned['charges'],
    q=4,
    labels=False
)

# List of categorical (encoded) features
# Corrected to match the actual column names after one-hot encoding
cat_features = [
    'is_female',
    'is_smoker',
    'region_northwest',
    'region_southeast',
    'region_southwest',
    'bmi_category_healthy', # Corrected
    'bmi_category_overweight', # Corrected
    'bmi_category_obese' # Corrected
]

# Dictionary to store Chi-Square test results
chi2_results = {}

# Loop through each categorical feature
for col in cat_features:

    # Create contingency table
    contingency = pd.crosstab(
        df_cleaned[col],
        df_cleaned['charges_bin']
    )

    # Apply Chi-Square test
    chi2_stat, p_val, _, _ = chi2_contingency(contingency)

    # Make decision based on p-value
    decision = (
        'Reject Null (Keep Feature)'
        if p_val < alpha
        else 'Accept Null (Drop Feature)'
    )

    # Store results in dictionary
    chi2_results[col] = {
        'chi2_statistic': chi2_stat,
        'p_value': p_val,
        'Decision': decision
    }

    chi2_df = pd.DataFrame(chi2_results).T
chi2_df = chi2_df.sort_values(by='p_value')
